import { NAME_MAX_LENGTH } from '@airsong/protocol';
import { TransportStateEnum, ViewerStateEnum } from '@airsong/sender-core';

import { userMessageFor } from './errors.js';
import { canHostLocal } from './host.js';
import { renderQrSvg } from './qr.js';
import { createSharingController, SharePhaseEnum, type ShareStateType, type SharingControllerType } from './sharing.js';
import { isSharingSupported, sharingSupportNote } from './support.js';
import './styles.css';
import { button, create, mount } from './ui/dom.js';

function transportStatusText(state: TransportStateEnum | null): string {
  switch (state) {
    case TransportStateEnum.CONNECTED:
      return 'Live';
    case TransportStateEnum.CONNECTING:
      return 'Connecting…';
    case TransportStateEnum.RECONNECTING:
      return 'Reconnecting…';
    default:
      return 'Offline';
  }
}

function viewerStateText(state: ViewerStateEnum): string {
  switch (state) {
    case ViewerStateEnum.CONNECTED:
      return 'connected';
    case ViewerStateEnum.CONNECTING:
      return 'connecting…';
    case ViewerStateEnum.DISCONNECTED:
      return 'reconnecting…';
    default:
      return '';
  }
}

function renderStart(controller: SharingControllerType, state: ShareStateType): Node[] {
  const children: Node[] = [];

  if (state.phase === SharePhaseEnum.ERROR && state.errorKind !== null) {
    children.push(create('p', { className: 'error', text: userMessageFor(state.errorKind) }));
  }

  const nameInput = create('input', {
    className: 'field',
    attrs: { type: 'text', placeholder: 'Device name (optional)', maxlength: String(NAME_MAX_LENGTH) },
  });

  const discoverable = create('input', { attrs: { type: 'checkbox' } });
  discoverable.checked = state.discoverable;
  discoverable.addEventListener('change', (): void => {
    controller.setDiscoverable(discoverable.checked);
  });
  const discoverableLabel = create('label', { className: 'toggle' });
  discoverableLabel.append(discoverable, create('span', { text: 'Visible to nearby devices' }));

  children.push(nameInput, discoverableLabel);

  if (__AIRSONG_TEST_TONE__) {
    const testTone = create('input', { attrs: { type: 'checkbox' } });
    testTone.checked = state.useTestTone;
    testTone.addEventListener('change', (): void => {
      controller.setUseTestTone(testTone.checked);
    });
    const testToneLabel = create('label', { className: 'toggle' });
    testToneLabel.append(testTone, create('span', { text: 'Use test tone (dev)' }));
    children.push(testToneLabel);
  }

  const canStart = isSharingSupported() || __AIRSONG_TEST_TONE__;
  const starting = state.phase === SharePhaseEnum.STARTING;
  const startButton = button(starting ? 'Starting…' : 'Start sharing', 'btn btn--primary', (): void => {
    void controller.start(nameInput.value);
  });
  startButton.disabled = starting || !canStart;
  children.push(startButton);

  return children;
}

function renderSharing(controller: SharingControllerType, state: ShareStateType, code: string): Node[] {
  const children: Node[] = [];
  const url = `${window.location.origin}/r/${code}`;

  children.push(create('p', { className: 'status', text: transportStatusText(state.transportState) }));
  children.push(create('p', { className: 'code-label', text: 'Session code' }));
  children.push(create('p', { className: 'code', text: code }));

  const qr = create('div', { className: 'qr' });
  // The SVG and the encoded URL are both generated by this app — no untrusted input.
  qr.innerHTML = renderQrSvg(url);
  children.push(qr);
  children.push(create('p', { className: 'url', text: url }));

  children.push(create('h2', { className: 'subtitle', text: `Listeners (${String(state.viewers.length)})` }));
  const list = create('ul', { className: 'viewers' });
  if (state.viewers.length === 0) {
    list.append(create('li', { className: 'viewers__empty', text: 'No one has joined yet.' }));
  } else {
    for (const viewer of state.viewers) {
      list.append(
        create('li', { className: 'viewers__item', text: `${viewer.name} — ${viewerStateText(viewer.state)}` }),
      );
    }
  }
  children.push(list);

  children.push(
    button('Stop', 'btn btn--ghost', (): void => {
      void controller.stop();
    }),
  );
  return children;
}

function renderApp(root: HTMLElement, controller: SharingControllerType, state: ShareStateType): void {
  const children: Node[] = [create('h1', { className: 'title', text: 'Airsong Sender' })];
  children.push(create('p', { className: 'mode', text: `Mode: ${canHostLocal() ? 'Web + Local' : 'Web'}` }));

  const note = sharingSupportNote();
  if (note !== null) {
    children.push(create('p', { className: 'note', text: note }));
  }

  if (state.phase === SharePhaseEnum.SHARING && state.code !== null) {
    children.push(...renderSharing(controller, state, state.code));
  } else {
    children.push(...renderStart(controller, state));
  }
  mount(root, ...children);
}

function main(): void {
  const root = document.getElementById('app');
  if (root === null) {
    return;
  }
  const controller = createSharingController();
  controller.subscribe((state): void => {
    renderApp(root, controller, state);
  });
}

main();
